export const MODEL_TRAINING_TOTAL = MODEL_TRAINING_QUESTIONS.length;
export function modelTrainingSystem(question: ModelTrainingQuestion): SystemId {
  const n = Number(question.id.slice(6));
  if (n <= 5) return "cardiac";
  if (n <= 8) return "arterial";
  if (n <= 11) return "venous";
  if (n <= 21) return "respiratory";
  if (n === 22) return "muscular";
  if (n <= 45) return "skeletal";
  if (n <= 47) return "nervous";
  if (n <= 49) return "digestive";
  return "urinary";
}
export function isModelTrainingAnswer(
  question: ModelTrainingQuestion,
  partId: string,
  concepts: { id: string; elements: string[] }[],
) {
  return !!concepts
    .find((c) => c.id === question.conceptId)
    ?.elements.includes(partId);
}
export function shuffledModelQuestions(
  items: ModelTrainingQuestion[],
  count = 10,
  random = Math.random,
) {
  return [...items]
    .sort(() => random() - 0.5)
    .slice(0, Math.min(count, items.length));
}
